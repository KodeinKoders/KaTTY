#!/usr/bin/env bash
#
# Regenerates the Java FFM bindings of libghostty-vt from its C headers, and the Kotlin GhosttyKey
# enum from the key list in the headers.
#
# Run it after every libghostty-vt update (see libghostty-vt/README.adoc), and commit the result.
#
# Needs jextract for JDK 25 (https://jdk.java.net/jextract/): either on the PATH, or give its
# location with the JEXTRACT environment variable.
set -euo pipefail

cd "$(dirname "$0")/.."

JEXTRACT="${JEXTRACT:-jextract}"
INCLUDE=libghostty-vt/include
JAVA_OUT=ghostty-vt/src/main/java
KOTLIN_OUT=ghostty-vt/src/main/kotlin/app/katty/ghostty

if ! command -v "$JEXTRACT" > /dev/null; then
    echo "jextract not found: put it on the PATH or set JEXTRACT to its location." >&2
    exit 1
fi

# No --library option: the generated code looks symbols up with SymbolLookup.loaderLookup(), which
# finds them once NativeLibrary has called System.load on the dylib. Hardcoding a library name or
# path here would bypass the classpath-resource loading.
rm -rf "$JAVA_OUT/app/katty/ghostty/ffm"
"$JEXTRACT" \
    --output "$JAVA_OUT" \
    --target-package app.katty.ghostty.ffm \
    --header-class-name GhosttyVt \
    -I "$INCLUDE" \
    "$INCLUDE/ghostty/vt.h"

# The GhosttyKey enum values are implicit (sequential) in the header, so jextract only exposes them
# as individual constants. The enum is generated from the same list, and takes each code from the
# generated constant so that it follows the header.
{
    cat <<'HEADER'
// Generated by ghostty-vt/jextract.sh from ghostty/vt/key/event.h - do not edit.
package app.katty.ghostty

import app.katty.ghostty.ffm.GhosttyVt

/**
 * A physical key, named after the W3C UI Events `KeyboardEvent.code` values.
 */
public enum class GhosttyKey(internal val code: Int) {
HEADER
    awk '
        /GHOSTTY_KEY_UNIDENTIFIED/ { inside = 1 }
        inside && /} GhosttyKey;/ { inside = 0 }
        inside && match($0, /GHOSTTY_KEY_[A-Z0-9_]+/) {
            name = substr($0, RSTART, RLENGTH)
            if (name !~ /_MAX_VALUE$/) {
                short = substr(name, length("GHOSTTY_KEY_") + 1)
                printf "    %s(GhosttyVt.%s()),\n", short, name
            }
        }
    ' "$INCLUDE/ghostty/vt/key/event.h"
    echo "}"
} > "$KOTLIN_OUT/GhosttyKey.kt"

echo "Generated $(find "$JAVA_OUT/app/katty/ghostty/ffm" -name '*.java' | wc -l | tr -d ' ') Java files and $KOTLIN_OUT/GhosttyKey.kt"
